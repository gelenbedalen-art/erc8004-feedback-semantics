// Concatenates the library into one dependency-free browser script (used by the demo page).
// Usage: node --experimental-strip-types scripts/bundle.ts > docs/lib.js
import { readFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";

const ORDER = ["tags", "normalize", "ndjson", "abi", "chain", "census", "analyze", "report"];

export function bundle(root = new URL("../src/", import.meta.url)): string {
  const parts = ORDER.map((name) => {
    const ts = readFileSync(new URL(`${name}.ts`, root), "utf8");
    const js = stripTypeScriptTypes(ts, { mode: "strip" });
    return `// ---- src/${name}.ts ----\n` + js
      .replace(/^import[\s\S]*?from\s+"[^"]+";\s*$/gm, "")
      .replace(/^export\s+\{[^}]*\}\s+from\s+"[^"]+";\s*$/gm, "")
      .replace(/^export\s+(?=(const|function|async|class|let)\b)/gm, "");
  });
  return `// erc8004-feedback-semantics browser bundle (generated by scripts/bundle.ts, MIT)\n"use strict";\nconst ERC8004FS = (() => {\n${parts.join("\n")}\nreturn { TAG_RULES, ruleFor, normalize, summarize, fromNdjson, toNdjson, ARC, getClients, readAllFeedback, getSummary, runCensus, analyze, render, PUBLISHED_PRIOR };\n})();\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) process.stdout.write(bundle());
